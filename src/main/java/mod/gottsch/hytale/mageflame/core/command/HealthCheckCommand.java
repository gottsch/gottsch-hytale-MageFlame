package mod.gottsch.hytale.mageflame.core.command;

import com.hypixel.hytale.protocol.GameMode;
import com.hypixel.hytale.server.core.Message;
import com.hypixel.hytale.server.core.command.system.CommandContext;
import com.hypixel.hytale.server.core.command.system.basecommands.CommandBase;

import javax.annotation.Nonnull;

/**
 * /mageflame healthcheck - confirms the plugin is loaded and reports its version.
 *
 * @author Mark Gottschling on 1/21/2026
 */
public class HealthCheckCommand extends CommandBase {
    private final String pluginName;
    private final String pluginVersion;

    public HealthCheckCommand(String pluginName, String pluginVersion) {
        super("healthcheck", "A simple health check from the " + pluginName + " plugin.");
        // allow anyone to run command
        this.setPermissionGroup(GameMode.Adventure);
        this.pluginName = pluginName;
        this.pluginVersion = pluginVersion;
    }

    @Override
    protected void executeSync(@Nonnull CommandContext context) {
        context.sendMessage(Message.raw(pluginName + " v" + pluginVersion + " plugin says hello!"));
    }
}
